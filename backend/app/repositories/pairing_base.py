"""Repository interfaces for device-pairing state (spec v1.1 pass 4,
mandatory correction 1).

Before this pass, `app/services/device_pairing.py` stored pairing codes and
device tokens directly in two process-local `dict`s. That is not
production-safe for exactly the reasons a demo backend can otherwise get
away with in-memory state elsewhere in this repository (see
`InMemoryRaceStateRepository`'s own docstring) — EXCEPT that pairing state
does not have the same "single active run, single writer" shape race state
does:

  * A backend restart (a deploy, an ECS task recycle) invalidates every
    already-paired Fire TV, because the device tokens it was relying on
    simply vanish.
  * An ECS service normally runs more than one task behind a load balancer.
    A pairing code generated by (or a device token verified against) one
    task is invisible to another task handling the next request.
  * Two tasks racing to consume the SAME pairing code, or apply the SAME
    revocation, have no shared state to coordinate through.

This module defines the storage-agnostic interfaces
(`PairingCodeRepository`, `DeviceTokenRepository`) that
`app/services/device_pairing.py` now depends on instead of a hardcoded
`dict`. Two implementations exist:

  * `app/repositories/pairing_memory.py` — the original in-process
    behavior, preserved byte-for-byte in spirit (thread-safe via a
    `threading.Lock`, no persistence across restarts). This remains the
    default for local development (`STATE_REPOSITORY=memory`) so nothing
    about the local dev experience changes.
  * `app/repositories/pairing_dynamodb.py` — a real, durable, multi-task
    -safe implementation backed by the SAME DynamoDB table race state and
    watches/alerts already use (see that module's docstring for the item
    shapes and the AWS partition key scheme), selected automatically when
    `STATE_REPOSITORY=dynamodb` (or explicitly via `PAIRING_REPOSITORY` —
    see `app/config.py`).

`PairingCodeRepository.try_consume_code` is the one method whose contract
matters most: it must atomically flip a still-valid, not-yet-used code to
"used" and report whether THIS caller was the one that did it, so that two
concurrent `POST /v1/auth/pair` requests presenting the same code can never
both succeed. The in-memory implementation gets this "for free" from
Python's GIL plus an explicit lock; the DynamoDB implementation gets it
from a conditional `UpdateItem` (`ConditionExpression="used = :false"`),
which DynamoDB guarantees is atomic even across concurrently-running ECS
tasks with no shared process memory at all.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass
from enum import Enum
from typing import Optional


@dataclass(frozen=True)
class StoredPairingCode:
    code_hash: str
    created_at: float
    expires_at: float
    used: bool


@dataclass(frozen=True)
class StoredDeviceToken:
    device_id: str
    token_hash: str
    device_name: str
    created_at: float
    expires_at: float
    revoked: bool


class PairingCodeRepository(ABC):
    """Storage for one-time, short-lived pairing codes. Only a SHA-256
    hash of the code is ever passed in or stored here — see
    `device_pairing.py`'s `_hash` and its docstring for why a fast hash is
    an appropriate trade-off for this value's entropy/lifetime."""

    @abstractmethod
    def create_code(self, code_hash: str, created_at: float, expires_at: float) -> bool:
        """Stores a freshly-issued, not-yet-used code, IF `code_hash` does
        not already belong to another currently-active code (unused and
        not yet expired). Returns True iff the code was actually stored;
        False means the 6-digit code this hash represents collided with a
        still-active code already outstanding for someone else, and the
        caller (`DevicePairingService.generate_pairing_code` -- see
        AWS hackathon-final pass, P1-11) must generate a fresh,
        independently-random code and retry rather than silently
        overwriting the still-live code a different pairing session is
        relying on. A hash that belongs to an EXPIRED or already-USED
        code is safe to recycle/overwrite (implementations must allow
        this -- 6-digit codes are a small enough space, and codes expire
        often enough, that permanently retiring a value the moment it is
        ever issued once would exhaust the space over the life of a
        deployment for no security benefit)."""

    @abstractmethod
    def try_consume_code(self, code_hash: str, now: float) -> bool:
        """Atomically marks the code used IF AND ONLY IF it exists, is not
        already used, and has not expired. Returns True iff THIS call
        performed the consumption (i.e. is the exchange allowed to
        proceed) — a concurrent caller racing for the same code_hash must
        never also receive True."""


class DeviceTokenRepository(ABC):
    """Storage for device-specific tokens minted by a successful pairing
    exchange. Only a SHA-256 hash of the token is ever passed in or stored
    here."""

    @abstractmethod
    def create_token(
        self,
        device_id: str,
        token_hash: str,
        device_name: str,
        created_at: float,
        expires_at: float,
    ) -> None:
        """Stores a freshly-minted, not-revoked device token."""

    @abstractmethod
    def get_token(self, token_hash: str) -> Optional[StoredDeviceToken]:
        """Returns the stored record for this token hash, or None if no
        such token was ever issued. Callers must still check
        `.revoked`/`.expires_at` themselves (kept as a plain read here so
        it composes with both `verify_token_hash` and diagnostics)."""

    @abstractmethod
    def revoke_token(self, token_hash: str) -> bool:
        """Self-revoke by token hash. Returns True iff a real,
        not-already-revoked token was found and revoked."""

    @abstractmethod
    def revoke_by_device_id(self, device_id: str) -> bool:
        """Admin revoke by device_id, independent of any other device's
        token. Returns True iff a real, not-already-revoked device was
        found and revoked."""


class PairingExchangeOutcome(Enum):
    """AWS hackathon-final pass, phase 3: the result of one attempted
    `PairingExchangeCoordinator.atomic_exchange` call.

    SUCCESS is the only outcome under which anything was actually
    persisted — CODE_REJECTED / DEVICE_ID_COLLISION / TOKEN_HASH_COLLISION
    all mean the transaction made NO change whatsoever (crucially,
    including: the pairing code was NOT consumed), so a caller retrying
    after either collision outcome is always safe."""

    SUCCESS = "success"
    CODE_REJECTED = "code_rejected"  # unknown / already-used / expired code — do not retry with the same code
    DEVICE_ID_COLLISION = "device_id_collision"  # retry the whole exchange with a fresh device_id
    # This is an enum member's string VALUE (an outcome label), not a
    # credential -- retry the whole exchange with a fresh device token.
    TOKEN_HASH_COLLISION = "token_hash_collision"  # nosec B105


class PairingExchangeCoordinator(ABC):
    """AWS hackathon-final pass, phase 3: closes the "fully transactional
    pairing exchange" gap. Before this pass, `DevicePairingService.
    exchange_pairing_code` called `PairingCodeRepository.try_consume_code`
    (consuming the one-time code) and THEN, as a separate, later call,
    `DeviceTokenRepository.create_token` (minting the device token). If
    the process crashed, threw, or lost its DynamoDB connection between
    those two calls — or if `create_token`'s own write failed for any
    reason, including the vanishingly rare token_hash/device_id collision
    case — the one-time code had ALREADY been permanently burned with no
    device token ever produced, and the person reading that code off a
    Fire TV screen has no way to get a working pairing out of it: the
    code cannot be reused (correctly — it truly was consumed) and no
    token exists to fall back on.

    This interface instead performs code-consumption + device-token
    creation + device-id-index creation as ONE atomic operation. Either
    every one of those three effects lands, or NONE of them do — there is
    no code-burned-but-no-token intermediate state visible to any other
    caller, ever, including across a crash mid-operation (an
    implementation must use a single atomic backend operation for this,
    e.g. one DynamoDB `TransactWriteItems` call — see
    `pairing_dynamodb.py`'s `DynamoDBPairingExchangeCoordinator`)."""

    @abstractmethod
    def atomic_exchange(
        self,
        *,
        code_hash: str,
        now: float,
        device_id: str,
        token_hash: str,
        device_name: str,
        token_expires_at: float,
    ) -> PairingExchangeOutcome:
        """Attempts to atomically: (1) mark the code identified by
        `code_hash` used, IF AND ONLY IF it currently exists, is unused,
        and has not expired (as of `now`); (2) create a device-token
        record for `token_hash`, IF AND ONLY IF `token_hash` is not
        already in use by another device token; (3) create a device-id
        index record for `device_id`, IF AND ONLY IF `device_id` is not
        already in use by another device.

        Returns PairingExchangeOutcome.SUCCESS iff all three conditions
        held and all three effects were applied together. Otherwise
        returns whichever single outcome best explains the rejection
        (CODE_REJECTED takes priority when the code itself was invalid,
        since that is never resolved by picking fresh random values and
        retrying) — and, critically, leaves EVERY piece of state
        completely unchanged, including the pairing code's own
        `used`/`expires_at` fields, so the caller may safely retry the
        whole exchange (with a freshly generated device_id and/or
        token_hash, per `PAIRING_CODE_GENERATION_MAX_ATTEMPTS`-style
        bounded retries) without any risk of double-consuming the code or
        leaking an orphaned token/index record from the failed attempt."""
